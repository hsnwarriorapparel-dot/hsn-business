#!/usr/bin/env python3
import json
import re

# Load the skills data
with open('/home/ubuntu/skills_list.json', 'r') as f:
    data = json.load(f)

skills = data.get('skills', [])

print(f"Total skills: {len(skills)}")

# Let's first check a few skills to see their descriptions
for i, skill in enumerate(skills[:5]):
    print(f"{i}: {skill['name']} - {skill['description'][:100]}...")

# Define relevance keywords - MORE SPECIFIC THIS TIME
# Focus on skills that directly contribute to professional, human website design without AI slop
design_keywords = ['design', 'visual', 'template', 'slop', 'aesthetic', 'ui', 'ux', 'interface', 'layout', 'typography', 'spacing', 'shadow', 'animation', 'card', 'color', 'font', 'graphics', 'diagram', 'wireframe', 'mockup', 'prototype']
copywriting_keywords = ['copy', 'writing', 'human', 'ai-ism', 'tone', 'voice', 'persuasive', 'marketing', 'headline', 'cta', 'tagline', 'hero', 'sentence', 'paragraph', 'grammar', 'style']
ux_keywords = ['ux', 'user experience', 'accessibility', 'interaction', 'guideline', 'usability', 'wcga', 'screen reader', 'navigation', 'usability']
tech_keywords = ['frontend', 'frontend-design', 'website-build', 'redesign', 'upgrade', 'premium', 'professional']
redesign_keywords = ['redesign', 'upgrade', 'premium', 'existing', 'revamp', 'professional']
seo_keywords = ['seo', 'search', 'visibility', 'ranking', 'traffic', 'google', 'meta', 'keyword']
ai_slop_keywords = ['ai slop', 'ai-ism', 'humanize', 'templated', 'generic']

relevant_skills = []

for skill in skills:
    name = skill.get('name', '')
    desc = skill.get('description', '')
    desc_lower = desc.lower()
    
    # Check relevance - must match at least one category
    relevant = False
    matched_categories = []
    
    if any(kw in desc_lower for kw in design_keywords):
        relevant = True
        matched_categories.append('design')
    if any(kw in desc_lower for kw in copywriting_keywords):
        relevant = True
        matched_categories.append('copywriting')
    if any(kw in desc_lower for kw in ux_keywords):
        relevant = True
        matched_categories.append('ux')
    if any(kw in desc_lower for kw in tech_keywords):
        relevant = True
        matched_categories.append('technical')
    if any(kw in desc_lower for kw in redesign_keywords):
        relevant = True
        matched_categories.append('redesign')
    if any(kw in desc_lower for kw in seo_keywords):
        relevant = True
        matched_categories.append('seo')
    if any(kw in desc_lower for kw in ai_slop_keywords):
        relevant = True
        matched_categories.append('ai-slop')
    
    if relevant:
        relevant_skills.append((name, desc, matched_categories))

print(f"\nRelevant skills: {len(relevant_skills)}")

# Show first few for verification
for i, (name, desc, cats) in enumerate(relevant_skills[:10]):
    print(f"{i}: {name} - {cats}")
    print(f"   {desc[:80]}...")
    print()

# Generate markdown
with open('/home/ubuntu/.hermes/plans/2026-10-08_143000-professional-website-skills-executed.md', 'w') as f:
    f.write('# Professional Website Creation Skills (No AI Slop)\n\n')
    f.write('## Goal\n')
    f.write('Identify Hermes Agent skills that enable creation of professional, human-touch websites without AI slop.\n\n')
    f.write('## Relevant Skills\n\n')
    
    for name, desc, cats in relevant_skills:
        f.write(f'### {name}\n\n')
        f.write(f'{desc}\n\n')
        f.write(f'*Relevance: {", ".join(cats)}*\n\n')
        f.write('---\n\n')
    
    f.write('## Notes\n\n')
    f.write('- This list was generated by filtering skills based on keyword matches in their descriptions.\n')
    f.write('- Skills were selected if they contained terms related to design, copywriting, UX, technical quality, redesign, SEO, or anti-AI-slop.\n')
    f.write('- The goal is to identify skills that help create professional, human-touch websites without AI slop.\n')

print(f"Markdown file written to: /home/ubuntu/.hermes/plans/2026-10-08_143000-professional-website-skills-executed.md")