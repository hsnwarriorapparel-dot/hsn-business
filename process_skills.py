#!/usr/bin/env python3
import json
import re

# Load the skills data
with open('/home/ubuntu/skills_list.json', 'r') as f:
    data = json.load(f)

skills = data.get('skills', [])

# Define relevance keywords
design_keywords = ['design', 'visual', 'template', 'slop', 'aesthetic', 'ui', 'ux', 'interface', 'layout', 'typography', 'spacing', 'shadow', 'animation', 'card', 'color', 'font']
copywriting_keywords = ['copy', 'writing', 'human', 'ai-ism', 'tone', 'voice', 'persuasive', 'marketing', 'headline', 'cta', 'tagline', 'hero']
ux_keywords = ['ux', 'user experience', 'accessibility', 'interaction', 'guideline', 'usability', 'wcga', 'screen reader']
tech_keywords = ['audit', 'optimize', 'performance', 'standard', 'quality', 'code', 'debug', 'test', 'validate', 'architecture', 'refactor']
redesign_keywords = ['redesign', 'upgrade', 'premium', 'existing', 'revamp']
seo_keywords = ['seo', 'search', 'visibility', 'ranking', 'traffic', 'google', 'meta', 'keyword']

relevant_skills = []

for skill in skills:
    name = skill.get('name', '')
    desc = skill.get('description', '')
    desc_lower = desc.lower()
    
    # Check relevance
    relevant = False
    if any(kw in desc_lower for kw in design_keywords):
        relevant = True
    if any(kw in desc_lower for kw in copywriting_keywords):
        relevant = True
    if any(kw in desc_lower for kw in ux_keywords):
        relevant = True
    if any(kw in desc_lower for kw in tech_keywords):
        relevant = True
    if any(kw in desc_lower for kw in redesign_keywords):
        relevant = True
    if any(kw in desc_lower for kw in seo_keywords):
        relevant = True
    
    if relevant:
        relevant_skills.append((name, desc))

# Generate markdown
with open('/home/ubuntu/.hermes/plans/2026-10-08_143000-professional-website-skills-executed.md', 'w') as f:
    f.write('# Professional Website Creation Skills (No AI Slop)\n\n')
    f.write('## Goal\n')
    f.write('Identify Hermes Agent skills that enable creation of professional, human-touch websites without AI slop.\n\n')
    f.write('## Relevant Skills\n\n')
    
    for name, desc in relevant_skills:
        f.write(f'### {name}\n\n')
        f.write(f'{desc}\n\n')
        f.write('---\n\n')
    
    f.write('## Notes\n\n')
    f.write('- This list was generated by filtering skills based on keyword matches in their descriptions.\n')
    f.write('- Skills were selected if they contained terms related to design, copywriting, UX, technical quality, redesign, or SEO.\n')
    f.write('- The goal is to identify skills that help create professional, human-touch websites without AI slop.\n')

print(f"Found {len(relevant_skills)} relevant skills out of {len(skills)} total skills")
print("Markdown file written to: /home/ubuntu/.hermes/plans/2026-10-08_143000-professional-website-skills-executed.md")